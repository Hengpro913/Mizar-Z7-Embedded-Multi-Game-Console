`timescale 1ns / 1ps
//=============================================================================
// font_rom.v
//   8 x 8 ASCII font ROM, purely combinational.
//
//   Only the glyphs used by the game console are defined; every other code
//   returns a blank cell.
//
//   Convention:
//     bits[7] = LEFTMOST pixel of the cell, bits[0] = RIGHTMOST.
//     1 = foreground (draw) , 0 = background.
//     A 5-px-wide glyph sits in bits[7:3]; bits[2:0] are the inter-char gap.
//     row 0 = top row ... row 7 = bottom row.
//
//   Each glyph is packed as eight row-bytes with row 0 in the LOW byte, so
//   row "r" is simply  g[r*8 +: 8].
//=============================================================================
module font_rom (
    input  wire [7:0] ch,      // ASCII code
    input  wire [2:0] row,     // 0 = top ... 7 = bottom
    output wire [7:0] bits
);

    reg [63:0] g;

    always @(*) begin
        case (ch)
            //---------------- punctuation / blank -----------------
            8'h20: g = 64'h0000_0000_0000_0000;   // ' '
            8'h2D: g = 64'h0000_0000_F800_0000;   // '-'

            //---------------- digits 0..9 --------------------------
            8'h30: g = 64'h0070_88C8_A898_8870;   // '0'
            8'h31: g = 64'h0070_2020_2020_6020;   // '1'
            8'h32: g = 64'h00F8_4020_1008_8870;   // '2'
            8'h33: g = 64'h0070_8808_1020_10F8;   // '3'
            8'h34: g = 64'h0010_10F8_9050_3010;   // '4'
            8'h35: g = 64'h0070_8808_08F0_80F8;   // '5'
            8'h36: g = 64'h0070_8888_F080_4030;   // '6'
            8'h37: g = 64'h0040_4040_2010_08F8;   // '7'
            8'h38: g = 64'h0070_8888_7088_8870;   // '8'
            8'h39: g = 64'h0060_1008_7888_8870;   // '9'

            //---------------- letters used by the scenes -----------
            8'h41: g = 64'h0088_8888_F888_8870;   // 'A'
            8'h42: g = 64'h00F0_8888_F088_88F0;   // 'B'
            8'h43: g = 64'h0070_8880_8080_8870;   // 'C'
            8'h44: g = 64'h00F0_8888_8888_88F0;   // 'D'
            8'h45: g = 64'h00F8_8080_F080_80F8;   // 'E'
            8'h46: g = 64'h0080_8080_F080_80F8;   // 'F'
            8'h47: g = 64'h0078_8888_B880_8870;   // 'G'
            8'h48: g = 64'h0088_8888_F888_8888;   // 'H'
            8'h49: g = 64'h0070_2020_2020_2070;   // 'I'
            8'h4A: g = 64'h0070_8888_0808_0808;   // 'J'
            8'h4B: g = 64'h0088_90A0_C0A0_9088;   // 'K'
            8'h4C: g = 64'h00F8_8080_8080_8080;   // 'L'
            8'h4D: g = 64'h0088_8888_A8A8_D888;   // 'M'
            8'h4E: g = 64'h0088_8888_98A8_C888;   // 'N'
            8'h4F: g = 64'h0070_8888_8888_8870;   // 'O'
            8'h50: g = 64'h0080_8080_F088_88F0;   // 'P'
            8'h51: g = 64'h0068_90A8_8888_8870;   // 'Q'
            8'h52: g = 64'h0088_90A0_F088_88F0;   // 'R'
            8'h53: g = 64'h00F0_0808_7080_8078;   // 'S'
            8'h54: g = 64'h0020_2020_2020_20F8;   // 'T'
            8'h55: g = 64'h0070_8888_8888_8888;   // 'U'
            8'h56: g = 64'h0020_5088_8888_8888;   // 'V'
            8'h57: g = 64'h0088_D8A8_A888_8888;   // 'W'
            8'h58: g = 64'h0088_8850_2050_8888;   // 'X'
            8'h59: g = 64'h0020_2020_2050_8888;   // 'Y'
            8'h5A: g = 64'h0080_4020_1008_08F8;   // 'Z'

            default: g = 64'h0000_0000_0000_0000;
        endcase
    end

    assign bits = g[row*8 +: 8];

endmodule
